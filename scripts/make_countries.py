"""Country outlines for the countries globe slide: every Natural Earth 110m
admin-0 country as lon/lat rings, grouped by polygon (outer ring first,
holes after), so the slide can fill them and solve the enclosing cone of
any country's vertices live. The same Natural Earth release the globes'
coastlines come from, fetched into scripts/raw/ on first run.

GeoJSON rings are planar objects and need two repairs before a sphere can
read them. (1) The antimeridian cut: Antarctica's ring runs along latitude
-90 and up both sides of lng ±180; on the sphere those edges collapse to
one point and a doubled seam, so the pole points go and the seam
duplicates merge, leaving the coastline loop (the same merge drops the
repeated consecutive vertices some thirty other rings carry). (2) Winding: the globe
trusts it (CCW seen from outside encloses the ring's small side, CW the
rest of the sphere), Natural Earth writes outer rings CW, and a planar
shoelace cannot read a loop around a pole, so orientation is measured on
the sphere: the signed solid angle about the ring's own centroid. Slivers
with no area are dropped (North Korea carries a 3-point one).

Writes slides/data/countries.js.
"""
import json
from pathlib import Path

import numpy as np

from _fig import DATA, fetch, xyz

NE = 'https://cdn.jsdelivr.net/gh/nvkelso/natural-earth-vector@v5.1.2/geojson/ne_110m_admin_0_countries.geojson'
RAW = Path(__file__).resolve().parent / 'raw' / 'ne_110m_admin_0_countries.geojson'
POLE = 89.99      # a vertex this close to a pole is the cut, not the coast


def uncut(ring):
    """The ring without its antimeridian/polar cut: no pole vertices, no
    consecutive vertices that coincide on the sphere (lng ±180 included)."""
    pts = [(x, y) for x, y in ring if abs(y) < POLE]
    out = []
    for p in pts:
        if out and np.allclose(xyz(p[1], p[0]), xyz(out[-1][1], out[-1][0]), atol=1e-9):
            continue
        out.append(p)
    if len(out) > 1 and np.allclose(xyz(out[0][1], out[0][0]), xyz(out[-1][1], out[-1][0]), atol=1e-9):
        out.pop()
    return out


def solid_angle(ring):
    """Signed spherical area of the ring about its centroid: > 0 when the
    ring runs CCW seen from outside, enclosing its small side."""
    X = np.array([xyz(lat, lng) for lng, lat in ring])
    c = X.mean(axis=0); c /= np.linalg.norm(c)
    A, B = X, np.roll(X, -1, axis=0)
    num = np.einsum('ij,ij->i', np.cross(A, B), c[None, :])
    den = 1 + A @ c + B @ c + np.einsum('ij,ij->i', A, B)
    return float(np.sum(2 * np.arctan2(num, den)))


def oriented(ring, ccw):
    return ring if (solid_angle(ring) > 0) == ccw else ring[::-1]


def main():
    gj = json.loads(fetch(NE, RAW).read_text())
    out = []
    for f in gj['features']:
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        clean = []
        for poly in polys:
            rings = [uncut([(round(x, 4), round(y, 4)) for x, y in ring]) for ring in poly]
            rings = [r for r in rings if len(r) >= 3 and abs(solid_angle(r)) > 1e-9]
            if rings:
                clean.append([[list(p) for p in oriented(r, ccw=(k == 0))] for k, r in enumerate(rings)])
        out.append({'name': f['properties']['NAME'], 'polys': clean})
    out.sort(key=lambda c: c['name'])
    js = DATA / 'countries.js'
    js.write_text('// Generated by scripts/make_countries.py; do not edit.\n'
                  f'export const countries = {json.dumps(out, separators=(",", ":"))};\n')
    n = sum(len(r) for c in out for p in c['polys'] for r in p)
    print(f'wrote {js}: {len(out)} countries, {n} points, {js.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
