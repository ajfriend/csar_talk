"""Example cells for the per-cell slides: the roundest and the most squished
cell of H3 and S2 at the coarsest resolution that shows the system's real
spread (found by enumerating every cell: H3 res 2, S2 level 3; see plan.md).

Writes slides/data/cells.js, an ES module the slides import: keyed by the
slide's canvas id, each cell's boundary as [lng, lat] degrees and its AR
(recomputed here with csar). Framing is the library's job (view.fit).
"""
import json
from pathlib import Path

import csar
import h3
import s2sphere

OUT = Path(__file__).resolve().parent.parent / 'slides' / 'data' / 'cells.js'


def h3_verts(cid):
    return list(h3.cell_to_boundary(cid))           # (lat, lng) degrees


def s2_verts(token):
    cell = s2sphere.Cell(s2sphere.CellId.from_token(token))
    lls = [s2sphere.LatLng.from_point(cell.get_vertex(k)) for k in range(4)]
    return [(ll.lat().degrees, ll.lng().degrees) for ll in lls]


# canvas id -> (cell id, boundary)
CELLS = {
    'h3-low':  ('828007fffffffff', h3_verts),    # roundest hexagon at res 2
    'h3-high': ('82082ffffffffff', h3_verts),    # most squished hexagon at res 2
    's2-low':  ('0fc0000000000000', s2_verts),   # roundest cell at level 3
    's2-high': ('2ac0000000000000', s2_verts),   # most squished cell at level 3
}

cells = {}
for key, (cid, verts_of) in CELLS.items():
    verts = verts_of(cid)
    out = csar.solve(verts)                        # (lat, lng) pairs
    assert out.status == 'converged', (cid, out.status)
    cells[key] = {'id': cid, 'ar': round(out.aspect_ratio, 4),
                  'points': [[round(lng, 5), round(lat, 5)] for lat, lng in verts]}
    print(f'{key:8} {cid}  AR {out.aspect_ratio:.4f}  {len(verts)} vertices')

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text('// Generated by scripts/make_cell_examples.py; do not edit.\n'
               'export const cells = {\n'
               + ''.join(f'  {json.dumps(k)}: {json.dumps(v)},\n' for k, v in cells.items())
               + '};\n')
print('wrote', OUT)
