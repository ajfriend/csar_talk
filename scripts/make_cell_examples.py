"""Example cells for the per-cell slides: the roundest and the most squished
cell of H3 and S2 at the coarsest resolution that shows the system's real
spread (found by enumerating every cell: H3 res 2, S2 level 3; see plan.md).

Writes slides/data/cells.js, an ES module the slides import: one entry per
cell with its boundary as [lng, lat] degrees, its AR (recomputed here with
csar), and a camera distance that makes the cell fill about half the stage.
"""
import json
import math
from pathlib import Path

import csar
import h3
import numpy as np
import s2sphere

OUT = Path(__file__).resolve().parent.parent / 'slides' / 'data' / 'cells.js'

# (key, system, resolution, cell id, why)
CELLS = [
    ('h3-low', 'h3', 2, '828007fffffffff', 'roundest hexagon at res 2'),
    ('h3-high', 'h3', 2, '82082ffffffffff', 'most squished hexagon at res 2'),
    ('s2-low', 's2', 3, '0fc0000000000000', 'roundest cell at level 3'),
    ('s2-high', 's2', 3, '2ac0000000000000', 'most squished cell at level 3'),
]

# Stage geometry the slides use (see slides/style.css .stage): the camera
# distance is chosen so the cell's angular radius maps to this many px.
STAGE_W, STAGE_H = 1050, 600
TARGET_HALF_PX = 0.22 * STAGE_H


def boundary_latlng(system, res, cid):
    """The cell's vertices as (lat, lng) degrees, and its center."""
    if system == 'h3':
        assert h3.get_resolution(cid) == res
        return list(h3.cell_to_boundary(cid)), h3.cell_to_latlng(cid)
    cell_id = s2sphere.CellId.from_token(cid)
    assert cell_id.level() == res, (cid, cell_id.level())
    cell = s2sphere.Cell(cell_id)
    verts = []
    for k in range(4):
        ll = s2sphere.LatLng.from_point(cell.get_vertex(k))
        verts.append((ll.lat().degrees, ll.lng().degrees))
    c = s2sphere.LatLng.from_point(cell.get_center())
    return verts, (c.lat().degrees, c.lng().degrees)


def unit(lat, lng):
    a, b = math.radians(lat), math.radians(lng)
    return np.array([math.cos(a) * math.cos(b), math.cos(a) * math.sin(b), math.sin(a)])


def camera_dist(center, verts):
    """Distance along the cell's axis so its angular radius spans TARGET_HALF_PX.
    Perspective as in teec.js: a point at angle t from the view center lands at
    focal * sin t / (d - cos t) px from the middle, with focal = 1.15 * min(W, H)."""
    c = unit(*center)
    t = max(math.acos(min(1.0, float(np.dot(c, unit(*v))))) for v in verts)
    focal = 1.15 * min(STAGE_W, STAGE_H)
    return round(math.cos(t) + focal * math.sin(t) / TARGET_HALF_PX, 3)


entries = []
for key, system, res, cid, why in CELLS:
    verts, center = boundary_latlng(system, res, cid)
    out = csar.solve(verts)   # (lat, lng) pairs
    assert out.status == 'converged', (cid, out.status)
    entries.append({
        'key': key, 'system': system, 'res': res, 'id': cid, 'why': why,
        'ar': round(out.aspect_ratio, 4),
        'center': [round(center[1], 4), round(center[0], 4)],
        'points': [[round(lng, 5), round(lat, 5)] for lat, lng in verts],
        'dist': camera_dist(center, verts),
    })
    print(f'{key:8} {system} r{res} {cid}  AR {out.aspect_ratio:.4f}  {len(verts)} vertices  dist {entries[-1]["dist"]}')

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    '// Generated by scripts/make_cell_examples.py; do not edit.\n'
    '// One entry per example cell: boundary as [lng, lat] degrees, AR from csar,\n'
    '// and a camera distance that fills about half the stage.\n'
    'export const cells = ' + json.dumps(entries, indent=2) + ';\n'
    "export const byKey = Object.fromEntries(cells.map(c => [c.key, c]));\n")
print('wrote', OUT)
