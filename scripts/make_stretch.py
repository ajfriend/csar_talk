"""The stretch test: a square and a hexagon, each before and after a 1.5x
stretch along one axis, plus a spiky star as the foil. Two numbers for
each shape: the spherical IPQ, A(4pi-A)/P^2 (1 for a cap), and the
enclosing-ellipse aspect ratio.

Every shape lives on the sphere: tangent-plane coordinates placed by
central projection, with gnomonic circumradius SCALE, so the unstretched
shapes are ~40 degrees across and visibly curved on the live slides. AR
scales by exactly the stretch at any size (the stretch is a linear map of
3-space, which carries cones to cones); the spherical IPQ differs from the
planar 4piA/P^2 at this size, which is the point of drawing them big. AR
from csar, area from sparea, perimeter as the sum of the great-circle
edges.

Writes slides/data/shapes.js: each shape as [lng, lat] points with both
numbers, keyed by the slides' data-cell; the live slides draw them with
teec.js and caption them from the same object.
"""
import json

import csar
import numpy as np
import sparea

from _fig import DATA, lnglat

SCALE = 0.36        # tan(20°): gnomonic circumradius of the unstretched shapes
STRETCH = 1.5
# Square first: a 1.5x-stretched square is a 3:2 rectangle, and everyone already
# calls that 'aspect ratio 1.5'. Hexagon second: that is what DGGS cells are.
POLYGONS = [('square', 4, np.pi / 4), ('hexagon', 6, 0.0)]


def poly(n, phase):
    t = 2 * np.pi * np.arange(n) / n + phase
    return np.column_stack([np.cos(t), np.sin(t)])


def star(spikes=8, inner=0.45):
    """By symmetry its enclosing ellipse is a circle (AR 1), while its
    perimeter is long (low IPQ): the shape AR cannot see and IPQ can."""
    t = np.pi * np.arange(2 * spikes) / spikes + np.pi / 2
    r = np.where(np.arange(2 * spikes) % 2 == 0, 1.0, inner)
    return np.column_stack([r * np.cos(t), r * np.sin(t)])


def on_sphere(P):
    """Tangent-plane coords -> unit vectors near (1, 0, 0), by central projection."""
    X = np.column_stack([np.ones(len(P)), P[:, 0] * SCALE, P[:, 1] * SCALE])
    return X / np.linalg.norm(X, axis=1, keepdims=True)


def ipq(X):
    """Spherical isoperimetric quotient A(4pi-A)/P^2 on the unit sphere."""
    area = float(sparea.area(X, geo='vec3'))
    cos = np.clip(np.sum(X * np.roll(X, -1, axis=0), axis=1), -1, 1)
    perim = float(np.sum(np.arccos(cos)))
    return area * (4 * np.pi - area) / perim**2


def ar(X):
    r = csar.solve(X, geo='vec3')
    assert isinstance(r, csar.Converged), r
    return r.aspect_ratio


def shapes():
    """Every shape, in slide order: key -> its numbers and spherical points."""
    out = {}

    def add(key, P, sx=1.0):
        X = on_sphere(P * np.array([sx, 1.0]))
        out[key] = {'ipq': round(ipq(X), 3), 'ar': round(ar(X), 2), 'points': lnglat(X)}

    for name, n, ph in POLYGONS:
        add(name, poly(n, ph))
        add(name + '_stretched', poly(n, ph), STRETCH)
    add('star', star())
    return out


def main():
    S = shapes()
    lines = ['// Generated by scripts/make_stretch.py; do not edit.', 'export const shapes = {']
    lines += [f'  "{k}": {json.dumps(v, separators=(",", ":"))},' for k, v in S.items()]
    lines.append('};')
    out = DATA / 'shapes.js'
    out.write_text('\n'.join(lines) + '\n')
    for k, v in S.items():
        print(f'  {k:18s} IPQ {v["ipq"]:.3f}  AR {v["ar"]:.2f}')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
