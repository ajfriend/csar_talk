"""Globe data for the AR-on-the-globe slides: one DGGS system per globe,
every cell at one resolution.

The binaries are the dggs_compare data release's own: its site serves the
same files, in ajglobe's flat-binary polygon format (`globe--{key}_pos.f32`,
`_idx.u32`, `_ar.f32`, `_area.f32`; area is cell / the resolution's exact
mean 4π/N). This script downloads the ones the deck uses into
slides/data/globe/ (dropping the `globe--` prefix) and writes
slides/data/globes.js, the per-globe label and the ranges the slides' colour
scales need. Nothing is measured or reshaped here.
"""
import json

import numpy as np

from _fig import DATA, fetch

RELEASE = 'data-v11'
URL = f'https://github.com/ajfriend/dggs_compare/releases/download/{RELEASE}/globe--{{key}}_{{part}}'
OUT = DATA / 'globe'
PARTS = ['pos.f32', 'idx.u32', 'ar.f32', 'area.f32']

# the deck's globes: key in the release -> label on the slide
GLOBES = {
    'h3_r3': 'H3, resolution 3',
    's2_r6': 'S2, level 6',
    'isea7h_r4': 'ISEA7H, resolution 4',
    'ivea7h_r4': 'IVEA7H, resolution 4',
    'a5_r6': 'A5, resolution 6',
    'rhealpix_r4': 'rHEALPix, resolution 4',
}


def main():
    manifest = {}
    for key, label in GLOBES.items():
        for part in PARTS:
            fetch(URL.format(key=key, part=part), OUT / f'{key}_{part}')
        ar = np.fromfile(OUT / f'{key}_ar.f32', dtype='<f4')
        area = np.fromfile(OUT / f'{key}_area.f32', dtype='<f4')
        manifest[key] = {'label': label, 'ar': {'max': round(float(ar.max()), 3)},
                         'area': {'min': round(float(area.min()), 3), 'max': round(float(area.max()), 3)}}
    out = DATA / 'globes.js'
    out.write_text('// Generated by scripts/make_globes.py; do not edit.\n'
                   f'export const globes = {json.dumps(manifest, indent=1)};\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
